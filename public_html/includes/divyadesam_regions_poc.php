function divyadesam_poc_flat_list()
{
    global $DIVYADESAM_REGIONS_POC;
    $names = [];
    foreach ($DIVYADESAM_REGIONS_POC as $region) {
        foreach ($region['names'] as $name) {
            $names[] = $name;
        }
    }
    return $names;
}

function divyadesam_poc_tamil_label($name)
{
    $name = trim($name);
    $commaPos = strrpos($name, ',');
    if ($commaPos !== false) {
        $tamil = trim(substr($name, $commaPos + 1));
        if ($tamil !== '') {
            return $tamil;
        }
    }
    return $name;
}

function divyadesam_poc_english_label($name)
{
    $name = trim($name);
    $commaPos = strrpos($name, ',');
    if ($commaPos !== false) {
        return trim(substr($name, 0, $commaPos));
    }
    return $name;
}

function divyadesam_poc_norm($text)
{
    $text = str_replace(["\xC2\xA0", "\xE2\x80\x8B"], ' ', $text);
    $text = preg_replace('/\s+/u', '', trim($text));
    return $text;
}

/**
 * Map a DB DivyaDesam string to a canonical index, or null if unmatched.
 *
 * @return array{0: int, 1: int}|null [regionIndex, nameIndex]
 */
function divyadesam_poc_lookup($dbName)
{
    static $catalog = null;
    global $DIVYADESAM_REGIONS_POC;

    if ($catalog === null) {
        $catalog = [];
        foreach ($DIVYADESAM_REGIONS_POC as $ri => $region) {
            foreach ($region['names'] as $ni => $name) {
                $catalog[] = [
                    'ri' => $ri,
                    'ni' => $ni,
                    'full' => divyadesam_poc_norm($name),
                    'ta' => divyadesam_poc_norm(divyadesam_poc_tamil_label($name)),
                    'en' => strtolower(divyadesam_poc_norm(divyadesam_poc_english_label($name))),
                ];
            }
        }
    }

    $dbFull = divyadesam_poc_norm($dbName);
    $dbTa = divyadesam_poc_norm(divyadesam_poc_tamil_label($dbName));
    $dbEn = strtolower(divyadesam_poc_norm(divyadesam_poc_english_label($dbName)));

    foreach ($catalog as $row) {
        if ($row['full'] === $dbFull || $row['ta'] === $dbTa) {
            return [$row['ri'], $row['ni']];
        }
    }
    foreach ($catalog as $row) {
        if ($row['en'] !== '' && $row['en'] === $dbEn) {
            return [$row['ri'], $row['ni']];
        }
    }

    $best = null;
    $bestLen = 0;
    foreach ($catalog as $row) {
        if ($row['ta'] === '' || $dbTa === '') {
            continue;
        }
        if (mb_strpos($dbTa, $row['ta'], 0, 'UTF-8') !== false
            || mb_strpos($row['ta'], $dbTa, 0, 'UTF-8') !== false
        ) {
            $len = max(mb_strlen($row['ta'], 'UTF-8'), mb_strlen($dbTa, 'UTF-8'));
            if ($len > $bestLen) {
                $bestLen = $len;
                $best = [$row['ri'], $row['ni']];
            }
        }
    }
    return $best;
}

/**
 * Group DB DivyaDesam names into LIFCO regions. Unmatched names go last.
 *
 * @param list<string> $dbNames
 * @return list<array{label: string, count: int, names: list<string>}>
 */
function divyadesam_poc_ordered_groups(array $dbNames)
{
    global $DIVYADESAM_REGIONS_POC;

    $groups = [];
    foreach ($DIVYADESAM_REGIONS_POC as $region) {
        $groups[] = [
            'label' => $region['label'],
            'count' => $region['count'],
            'names' => [],
        ];
    }
    $other = [];

    foreach ($dbNames as $dbName) {
        $hit = divyadesam_poc_lookup($dbName);
        if ($hit === null) {
            $other[] = $dbName;
            continue;
        }
        [$ri, $ni] = $hit;
        $groups[$ri]['names'][$ni] = $dbName;
    }

    foreach ($groups as &$group) {
        ksort($group['names'], SORT_NUMERIC);
        $group['names'] = array_values($group['names']);
    }
    unset($group);

    if ($other !== []) {
        usort($other, function ($a, $b) {
            return strcmp(divyadesam_poc_tamil_label($a), divyadesam_poc_tamil_label($b));
        });
        $groups[] = [
            'label' => 'மற்றவை',
            'count' => count($other),
            'names' => $other,
        ];
    }

    return $groups;
}
